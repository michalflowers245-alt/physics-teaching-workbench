  function normalizeText(value) {
    return String(value || "").replace(/\s+/g, " ").toLocaleLowerCase("zh-CN").trim();
  }

  function evidenceText(question) {
    return [
      question?.stem,
      question?.options,
      question?.dataTables,
    ].flat(Infinity).map(item => typeof item === "object" && item !== null ? JSON.stringify(item) : item).filter(Boolean).join(" ").toLocaleLowerCase("zh-CN");
  }

  function promptEvidenceText(question) {
    const stem = String(question?.stem || "");
    // 目前多数历史卷把 A–D 选项也放在 stem 里。先切出真正的提问部分，
    // 防止一个干扰项中的“内能”或“质量”把整题挂到无关小节。
    const option = stem.match(/(?:^|[\s\n])[AＡ]\s*[.\uff0e、:：)]/);
    const prompt = option && option.index > 3 ? stem.slice(0, option.index) : stem;
    return prompt.toLocaleLowerCase("zh-CN");
  }

  function annotationText(question) {
    return [
      question?.mainPoint, question?.secondaryPoints, question?.physicalModel, question?.method,
      question?.confusedConcepts, question?.traps, question?.abilities,
    ].flat(Infinity).filter(Boolean).join(" ").toLocaleLowerCase("zh-CN");
  }

  function questionIsReviewed(question) {
    return question?.reviewed === true && Boolean(question?.reviewedBy) && Boolean(question?.reviewedAt) && !question?.excluded && !question?.mergedInto && !question?.migrationNeedsReview;
  }

  function occurrences(text, term) {
    if (!text || !term) return 0;
    let count = 0, offset = 0;
    while ((offset = text.indexOf(term, offset)) !== -1) {
      count += 1;
      offset += term.length;
      if (count >= 3) break;
    }
    return count;
  }

  function questionText(question) {
    return [
      question?.mainPoint, question?.secondaryPoints, question?.physicalModel, question?.method,
      question?.confusedConcepts, question?.traps, question?.stem, question?.answer,
      question?.abilities, question?.type,
    ].flat(Infinity).filter(Boolean).join(" ").toLocaleLowerCase("zh-CN");
  }

  function classifyQuestion(question, options = {}) {
    const rawEvidence = evidenceText(question);
    const promptEvidence = promptEvidenceText(question);
    const reviewed = questionIsReviewed(question);
    const reviewedAnnotations = reviewed ? annotationText(question) : "";
    if (!rawEvidence.trim() && !reviewedAnnotations.trim()) return [];
    const requestedBook = options.bookId || "";
    const explicitIds = Array.isArray(question?.curriculumNodeIds) ? question.curriculumNodeIds.filter(id => sectionMap.has(id)) : [];
    const explicitMatches = explicitIds
      .map(id => sectionMap.get(id))
      .filter(item => !requestedBook || item.bookId === requestedBook)
      .map(item => ({ id: item.id, score: 100, section: item, confirmed: reviewed && question?.curriculumMappingStatus === "confirmed" }));
    const ruleMatches = flatSections
      .filter(item => !requestedBook || item.bookId === requestedBook)
      .map(item => {
        let score = 0;
        let hasTopicEvidence = false;
        let peripheralSpecificMatches = 0;
        const title = item.title.toLocaleLowerCase("zh-CN");
        const mainPoint = normalizeText(question?.mainPoint);
        const titleLength = [...title].length;
        const pointLength = [...mainPoint].length;
        const reviewedTitleMatch = mainPoint === title || (titleLength >= 3 && mainPoint.includes(title)) || (pointLength >= 3 && title.includes(mainPoint));
        if (reviewed && mainPoint && reviewedTitleMatch) {
          score += 10;
          hasTopicEvidence = true;
        }
        if ([...title].length >= 3 && promptEvidence.includes(title)) {
          score += 6;
          hasTopicEvidence = true;
        }
        item.keywords.forEach((keyword, keywordIndex) => {
          const term = keyword.toLocaleLowerCase("zh-CN");
          if (!term) return;
          const promptHits = occurrences(promptEvidence, term);
          const allHits = occurrences(rawEvidence, term);
          const peripheralHits = Math.max(0, allHits - promptHits);
          const annotationHits = occurrences(reviewedAnnotations, term);
          const length = [...term].length;
          if (promptHits) {
            score += length >= 5 ? 5 : length >= 3 ? 4 : length >= 2 ? 2 : 1;
            score += Math.min(2, promptHits - 1);
            // 通用条件（质量、速度、时间等）即使反复出现也不能单独定类。
            if (!contextualKeywords.has(term)) {
              score += 2;
              hasTopicEvidence = true;
            }
          }
          if (peripheralHits && !contextualKeywords.has(term)) {
            peripheralSpecificMatches += 1;
            score += length >= 3 ? 2 : 1;
          }
          if (annotationHits) {
            score += length >= 4 ? 4 : length >= 2 ? 2 : 1;
            if (!contextualKeywords.has(term)) hasTopicEvidence = true;
          }
        });
        // 选项区中至少两个本节特异词共现，才将它视为备选主题；
        // 单个干扰项永远不足以定类。
        if (peripheralSpecificMatches >= 2) {
          score += 2;
          hasTopicEvidence = true;
        }
        return { id: item.id, score, section: item, hasTopicEvidence };
      })
      // 自动标签未审核时不作为归类证据；至少需要一个题干/答案中的主题证据。
      .filter(item => item.score >= 4 && item.hasTopicEvidence)
      .sort((a, b) => b.score - a.score || a.id.localeCompare(b.id));
    // 确认一个节点后仍保留其他规则候选，否则无法继续确认跨小节、
    // 跨教材与中考模型的多标签映射。
    const merged = [...explicitMatches, ...ruleMatches.filter(item => !explicitIds.includes(item.id))];
    return merged.slice(0, Math.min(options.limit || 6, 6));
  }

  function matchesQuestion(question, sectionId) {
    return classifyQuestion(question, { bookId: sectionMap.get(sectionId)?.bookId, limit: 10 }).some(item => item.id === sectionId);
  }

